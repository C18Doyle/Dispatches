// scene_map.mjs: a diagram of the scenes (by track) and a table of where every flag is set and read, written to SCENE_MAP.md (SCENE_MAP.mina.md for the other seat).
//   node scripts/scene_map.mjs            write the file
//   node scripts/scene_map.mjs --check    fail if the file on disk is not what the content would produce now (it is part of npm test)
// The diagram is Mermaid, which GitHub draws in a pull request or a file view. Solid arrows are options; a dashed arrow is a failed venture's own destination;
// a thick arrow goes into an ending. Locked options are marked. Run from the game folder; GAME=<seat> picks the seat.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const seat = process.env.GAME ?? "dracula";
const out = seat === "dracula" ? "SCENE_MAP.md" : `SCENE_MAP.${seat}.md`;
const dir = join("src", "content", seat);
const events = JSON.parse(readFileSync(join(dir, "events.json"), "utf8"));
const config = JSON.parse(readFileSync(join(dir, "config.json"), "utf8"));
const flavor = JSON.parse(readFileSync(join(dir, "flavor.json"), "utf8"));
const nodes = events.nodes;
const id = (s) => "n_" + s.replace(/[^A-Za-z0-9]/g, "_");
const eid = (s) => "e_" + s.replace(/[^A-Za-z0-9]/g, "_");
const esc = (s) => String(s).replace(/"/g, "'").replace(/[<>]/g, "");

const lines = [];
const P = (s = "") => lines.push(s);
P(`# Scene map: ${config.title}`);
P();
P("Generated by `scripts/scene_map.mjs` from the content files; do not edit by hand. `npm test` fails if it is out of date.");
P();
P(`${Object.keys(nodes).length} scenes, ${Object.keys(events.endings).length} endings. A scene is \`id: title\`; the number on an arrow is the option's position in the scene.`);
P();

// ---- the diagram ----
const branches = [...new Set(Object.values(nodes).map((n) => n.branch))];
P("```mermaid");
P("flowchart TD");
for (const b of branches) {
  P(`  subgraph ${b.replace(/[^A-Za-z0-9]/g, "_")}["${b}"]`);
  for (const n of Object.values(nodes)) if (n.branch === b) P(`    ${id(n.id)}["${esc(n.id)}: ${esc(n.title)}"]`);
  P("  end");
}
for (const e of Object.values(events.endings)) P(`  ${eid(e.id)}(["${esc(e.title)}"])`);
const seen = new Set();
const edge = (from, to, label, style) => {
  const k = `${from}|${to}|${label}|${style}`;
  if (seen.has(k)) return;
  seen.add(k);
  const target = to.startsWith("ENDING_") ? eid(to) : id(to);
  const arrow = to.startsWith("ENDING_") ? "==>" : style === "dashed" ? "-.->" : "-->";
  P(`  ${id(from)} ${arrow}|"${label}"| ${target}`);
};
for (const n of Object.values(nodes)) {
  n.options.forEach((o, i) => {
    const lock = o.requires || o.requiresFlag || o.gate || o.showWhen ? " (locked)" : "";
    const tag = o.roll ? " (venture)" : "";
    if (o.roll) {
      edge(n.id, o.roll.success.nextNodeId ?? o.nextNodeId, `${i}${lock}${tag}`, "solid");
      const f = o.roll.failure.nextNodeId ?? o.nextNodeId;
      if (f !== (o.roll.success.nextNodeId ?? o.nextNodeId)) edge(n.id, f, `${i} fails`, "dashed");
    } else edge(n.id, o.nextNodeId, `${i}${lock}`, "solid");
  });
}
for (const e of Object.values(events.endings)) P(`  class ${eid(e.id)} ${e.kind === "failure" ? "collapse" : "ending"}`);
P("  classDef ending fill:#efe9d6,stroke:#8a231f");
P("  classDef collapse fill:#2a1a1a,stroke:#8a231f,color:#eee");
P("```");
P();

// ---- the flags ----
const setBy = new Map();
const readBy = new Map();
const add = (m, flag, where) => m.set(flag, [...(m.get(flag) ?? []), where]);
const cond = (c, where) => {
  if (!c) return;
  if (c.flag) add(readBy, c.flag, where);
  for (const x of c.all ?? c.any ?? []) cond(x, where);
  if (c.not) cond(c.not, where);
};
for (const n of Object.values(nodes)) {
  (n.echoes ?? []).forEach((e) => cond(e.when, `${n.id} (echo)`));
  n.options.forEach((o, i) => {
    for (const f of o.setFlags ?? []) add(setBy, f, `${n.id}.${i}`);
    for (const r of o.roll ? [o.roll.success, o.roll.failure] : []) for (const f of r.setFlags ?? []) add(setBy, f, `${n.id}.${i}`);
    if (o.requiresFlag) add(readBy, o.requiresFlag, `${n.id}.${i} (lock)`);
    cond(o.requires, `${n.id}.${i} (lock)`);
    cond(o.showWhen, `${n.id}.${i} (shown when)`);
  });
}
for (const e of Object.values(events.endings)) (e.variants ?? []).forEach((v) => { if (v.flag) add(readBy, v.flag, `${e.id} (variant)`); cond(v.when, `${e.id} (variant)`); });
for (const t of config.trackers ?? []) {
  cond(t.showWhen, `counter: ${t.label}`);
  for (const r of t.rules) cond(r.when, `counter: ${t.label}`);
}
for (const r of config.epilogue?.inferredRules ?? []) cond(r.when, "epilogue");
for (const g of flavor.gossip) cond(g.when, "gossip");
if (config.assist?.favorFlag) add(setBy, config.assist.favorFlag, "the adviser's remedy");
const uniq = (a) => [...new Set(a)];
P("## Flags");
P();
P("| Flag | Set by (scene.option) | Read by | Note |");
P("|---|---|---|---|");
for (const f of [...setBy.keys()].sort()) {
  P(`| \`${f}\` | ${uniq(setBy.get(f)).join(", ")} | ${uniq(readBy.get(f) ?? ["nothing"]).join(", ")} | ${esc(flavor.flagNotes?.[f] ?? "")} |`);
}
P();
const text = lines.join("\n") + "\n";

if (process.argv.includes("--check")) {
  const now = existsSync(out) ? readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (now !== text) {
    console.error(`FAIL: ${out} is out of date. Run: node scripts/scene_map.mjs${seat === "dracula" ? "" : " (with GAME=" + seat + ")"}`);
    process.exit(1);
  }
  console.log(`${out} is current.`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}: ${Object.keys(nodes).length} scenes, ${setBy.size} flags.`);
}
