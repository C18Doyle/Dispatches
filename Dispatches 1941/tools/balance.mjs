#!/usr/bin/env node
// Balance report for Dispatches 1941: plays each command headlessly, many times, in several styles, on the game's own rules (logic.ts, strain
// included), and says where the design is lopsided. Ported from Dispatches 1940's tools/balance.mjs.
//
//   node tools/balance.mjs [runs] [--write]      (run `npm run build` first; 1500 runs a style takes about a minute)
//
// Per command, for each style of player (random, the historical choice every time, always the first, always the last, the choice with the best
// mean effect on the meters, and a gambler who takes a contested choice when there is one):
//   * how long the file is (decisions in a run: mean, shortest, longest) and how it ends (the most common ending and the tier it is worth);
//   * where the meters sit: the mean of each meter at the end, and the share of runs that end with a meter on the floor (-9 or worse);
//   * for random play, the first decision where more than a third of runs have a meter on the floor (a "pinned" meter has stopped being a
//     decision: nothing the player did made a difference to it);
//   * decisions where one order beats another by more than GAP points on the three meters taken together (a quiz, not a choice).
// With --write it also writes docs/BALANCE.md. It changes nothing in the game. Thresholds come from reading these numbers; do not tune by intuition.
import { writeFileSync } from "node:fs";
import { loadGame, seeded, AXES } from "./audit-lib.mjs";

const RUNS = Number(process.argv.find((a) => /^\d+$/.test(a)) || 1500);
const WRITE = process.argv.includes("--write");
const GAP = 4;
const FLOOR = -9;
const STYLES = ["random", "record", "first", "last", "greedy", "gambler"];
const game = await loadGame();
const { CAMPAIGNS, logic } = game;
const tier = (label) => (game.ENDING_CLASSIFICATION && game.ENDING_CLASSIFICATION[label]) || "no tier";

/** The mean change in the three meters of an order, weighting a contested one by its odds. */
function meanImpact(c) {
  if (c.uncertain && c.uncertain.length) {
    const total = c.uncertain.reduce((a, u) => a + u.weight, 0) || 1;
    return c.uncertain.reduce((s, u) => s + u.weight * logic.impactSum(u.impact || c.impact), 0) / total;
  }
  return logic.impactSum(c.impact);
}

/** One war, played in a style. Returns null if the war could not be played to the end. */
function play(campaignId, style, rnd, mode = "open") {
  const camp = CAMPAIGNS[campaignId];
  let flags = logic.startFlags(mode);
  let meters = { ...logic.EMPTY_METERS };
  let pos = camp.start;
  const trace = [];
  for (let step = 0; step < 400 && pos && pos !== "END"; step++) {
    let stage;
    try {
      stage = camp.resolveNode(pos, flags, meters);
    } catch (e) {
      return null;
    }
    if (!stage) return null;
    stage = logic.strainStage(logic.playableStage(stage, mode, 5), flags, meters);
    const open = stage.choices.map((c, i) => [c, i]).filter(([c]) => !c.disabledReason);
    if (!open.length) return null;
    let pick;
    if (style === "record") pick = open.find(([c]) => c.historical) || open[0];
    else if (style === "first") pick = open[0];
    else if (style === "last") pick = open[open.length - 1];
    else if (style === "greedy") pick = open.reduce((a, b) => (meanImpact(b[0]) > meanImpact(a[0]) ? b : a));
    else if (style === "gambler") pick = open.find(([c]) => c.uncertain && c.uncertain.length) || open[Math.floor(rnd() * open.length)];
    else pick = open[Math.floor(rnd() * open.length)];
    const res = logic.resolveChoice({ stage, index: pick[1], mode, favor: 5, defiance: 0, flags, meters, rand: rnd });
    if (!res) return null;
    flags = res.flags;
    meters = res.meters;
    trace.push({ id: String(pos), m: { ...meters } });
    const { nextPos, isEnd } = logic.nextPosition({ dynamic: true, position: pos, choice: stage.choices[pick[1]], rollIndex: res.rollIndex, mode, flags });
    if (isEnd) pos = "END";
    else pos = nextPos;
  }
  if (pos !== "END") return null;
  return { flags, meters, label: camp.positionLabel(flags, meters), trace };
}

const out = [];
const log = (s = "") => {
  console.log(s);
  out.push(s);
};
log("# Dispatches 1941: balance report");
log("");
log(`Generated by \`node tools/balance.mjs ${RUNS} --write\`: up to ${RUNS} runs a style, in standard mode, no battles planned (a battle is its own order here). Strain is in force, as in the game.`);
for (const cid of Object.keys(CAMPAIGNS)) {
  log("");
  log(`## ${cid}`);
  log("");
  log("| style | runs | decisions (mean / shortest / longest) | most common ending (tier) | share | mean end meters (readiness / pipeline / initiative) | end with a meter on the floor |");
  log("|---|---|---|---|---|---|---|");
  let randomTraces = [];
  for (const style of STYLES) {
    const rnd = seeded(1000 + STYLES.indexOf(style));
    const n = ["record", "first", "last", "greedy"].includes(style) ? Math.min(RUNS, 300) : RUNS;
    const titles = {};
    const meanM = { readiness: 0, pipeline: 0, initiative: 0 };
    let done = 0;
    let floored = 0;
    let total = 0;
    let shortest = Infinity;
    let longest = 0;
    const traces = [];
    for (let i = 0; i < n; i++) {
      const r = play(cid, style, rnd);
      if (!r || r.flags.purged) continue;
      done++;
      titles[r.label] = (titles[r.label] || 0) + 1;
      for (const k of AXES) meanM[k] += r.meters[k];
      if (AXES.some((k) => r.meters[k] <= FLOOR)) floored++;
      total += r.trace.length;
      shortest = Math.min(shortest, r.trace.length);
      longest = Math.max(longest, r.trace.length);
      if (style === "random") traces.push(r.trace);
    }
    if (style === "random") randomTraces = traces;
    if (!done) {
      log(`| ${style} | 0 | | | | | |`);
      continue;
    }
    const top = Object.entries(titles).sort((a, b) => b[1] - a[1])[0];
    log(`| ${style} | ${done} | ${(total / done).toFixed(1)} / ${shortest} / ${longest} | ${top[0]} (${tier(top[0])}) | ${((100 * top[1]) / done).toFixed(0)}% | ${AXES.map((k) => (meanM[k] / done).toFixed(1)).join(" / ")} | ${((100 * floored) / done).toFixed(0)}% |`);
  }
  // where a meter gets pinned, under random play: the share of runs with a meter on the floor after each decision
  const longest = Math.max(0, ...randomTraces.map((t) => t.length));
  const rows = [];
  for (let k = 0; k < longest; k++) {
    const at = randomTraces.filter((t) => t.length > k);
    if (at.length < RUNS * 0.2) break;
    const share = Object.fromEntries(AXES.map((a) => [a, 0]));
    for (const t of at) for (const a of AXES) if (t[k].m[a] <= FLOOR) share[a]++;
    rows.push({ k, share: Object.fromEntries(AXES.map((a) => [a, share[a] / at.length])) });
  }
  const pinned = AXES.map((a) => {
    const hit = rows.find((r) => r.share[a] > 1 / 3);
    return hit ? `${a} on the floor in over a third of runs from decision ${hit.k + 1}` : null;
  }).filter(Boolean);
  log("");
  log(pinned.length ? `Pinned meters under random play: ${pinned.join("; ")}.` : "No meter is pinned under random play.");

  // dominant orders: at each report reached, compare the mean effect of the best and the worst open order
  const seen = new Map();
  const rnd = seeded(77);
  const camp = CAMPAIGNS[cid];
  for (let i = 0; i < 400; i++) {
    let flags = logic.startFlags("open");
    let meters = { ...logic.EMPTY_METERS };
    let pos = camp.start;
    for (let step = 0; step < 400 && pos && pos !== "END"; step++) {
      let stage;
      try {
        stage = camp.resolveNode(pos, flags, meters);
      } catch (e) {
        break;
      }
      if (!stage) break;
      stage = logic.strainStage(logic.playableStage(stage, "open", 5), flags, meters);
      const open = stage.choices.map((c, j) => [c, j]).filter(([c]) => !c.disabledReason);
      if (!open.length) break;
      if (open.length >= 2 && !seen.has(String(pos))) seen.set(String(pos), open.map(([c]) => c));
      const [, index] = open[Math.floor(rnd() * open.length)];
      const res = logic.resolveChoice({ stage, index, mode: "open", favor: 5, defiance: 0, flags, meters, rand: rnd });
      if (!res) break;
      flags = res.flags;
      meters = res.meters;
      const { nextPos, isEnd } = logic.nextPosition({ dynamic: true, position: pos, choice: stage.choices[index], rollIndex: res.rollIndex, mode: "open", flags });
      if (isEnd) break;
      pos = nextPos;
    }
  }
  const dominant = [];
  for (const [id, open] of seen) {
    const scores = open.map(meanImpact);
    const spread = Math.max(...scores) - Math.min(...scores);
    if (spread > GAP) dominant.push(`${id} (${spread.toFixed(1)})`);
  }
  log("");
  log(`Decisions where one order beats another by more than ${GAP} points of meter in total: ${dominant.length} of ${seen.size}${dominant.length ? ": " + dominant.join(", ") : ""}.`);
}
if (WRITE) {
  writeFileSync(new URL("../docs/BALANCE.md", import.meta.url), out.join("\n") + "\n");
  console.log("written docs/BALANCE.md");
}
