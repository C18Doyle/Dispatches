#!/usr/bin/env node
// Balance report for Dispatches 1914: plays the engine headlessly, many times, in several styles, and says where the design is lopsided.
//
//   node tools/balance.mjs [runs] [--write]      (run `npm run build` first; 4000 runs a command takes about a minute)
//
// It reports, per command and in standard mode:
//   * how each way of playing ends: random, the record (always the historical order), always the first order, always the last, the order with the best
//     immediate effect on the meters, and a gambler (a contested order when there is one);
//   * how often each ending is reached under random play, and any ending reached under 2 per cent or never;
//   * the rank score (out of 100, from rankFor) of each way of playing, and for every decision the order that scores best against the one that scores
//     worst, with the gap: a gap over 12 points is a dominant order, which makes the decision a quiz and not a choice;
//   * how often each detour (a node reached only from a speculative order) is entered, and how many contested rolls and three-way decisions a run meets.
// With --write it also writes docs/BALANCE.md. It changes nothing in the game. Thresholds come from reading these numbers; do not tune from intuition.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(ROOT, "package.json"));
const { loadEngine } = require("./_load.js");
process.chdir(ROOT);
const E = loadEngine("dispatches-greatwar.jsx");
const RUNS = Number(process.argv.find((a) => /^\d+$/.test(a)) || 4000);
const WRITE = process.argv.includes("--write");
const GAP = 12;

// a seeded random generator, so two runs of the report agree
function rngFor(seed) { let s = seed >>> 0; return () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296; }; }

const impactSum = (c) => { const i = c.impact || {}; return (i.manpower || 0) + (i.munitions || 0) + (i.will || 0); };
const STYLES = {
  random: (open, rnd) => open[Math.floor(rnd() * open.length)],
  record: (open, rnd) => open.find((c) => c.historical) || open[0],
  first: (open) => open[0],
  last: (open) => open[open.length - 1],
  greedy: (open) => open.reduce((a, c) => (impactSum(c) > impactSum(a) ? c : a), open[0]),
  gambler: (open, rnd) => { const g = open.filter((c) => c.uncertain && c.uncertain.length); return g.length ? g[Math.floor(rnd() * g.length)] : open[Math.floor(rnd() * open.length)]; },
};

function play(cid, style, seed, track) {
  const rnd = rngFor(seed);
  const c = E.CAMPAIGNS[cid];
  let flags = {}, meters = E.emptyMeters(), hard = E.emptyHardState();
  let id = c.startNode, guard = 0;
  const taken = [], visited = [];
  let rolls = 0, threes = 0, decisions = 0;
  while (id && guard++ < 200) {
    const n = E.resolveNode(id, flags, meters, hard);
    if (!n) return null;
    visited.push(id);
    if (n.ending) {
      const rank = E.rankFor({ campaignId: cid, endingId: id, meters, hardState: hard, easy: false, taken });
      return { ending: id, score: rank ? rank.score : 0, taken, visited, rolls, threes, decisions };
    }
    const open = n.choices.filter((x) => !x.blocked);
    if (!open.length) return null;
    decisions++;
    if (n.choices.length >= 3) threes++;
    const ch = STYLES[style](open, rnd);
    if (ch.uncertain && ch.uncertain.length) rolls++;
    taken.push({ node: id, choice: ch.id });
    const r = E.chooseNext(cid, ch, flags, meters, hard, rnd);
    flags = r.flags; meters = r.meters; hard = r.hardState; id = r.nextId;
  }
  return null;
}

const pct = (n, d) => (d ? (100 * n) / d : 0);
const f1 = (x) => x.toFixed(1);
const out = [];
const log = (s = "") => { out.push(s); console.log(s); };

log(`# Balance of Dispatches 1914\n`);
log(`Generated by \`node tools/balance.mjs ${RUNS}\`: ${RUNS} runs a command for random play and for each other style, standard mode, seeded. Rank score is out of 100 (\`rankFor\`).\n`);

const summaryRows = [];
for (const cid of E.CAMPAIGN_IDS) {
  const c = E.CAMPAIGNS[cid];
  if (!Object.keys(c.nodes).length) continue;
  const endings = E.buildEndings().filter((e) => e.campaignId === cid);
  const settled = endings.find((e) => e.badge === E.BADGES.SETTLED);
  const nodeIds = Object.keys(c.nodes);
  const detours = nodeIds.filter((id) => !c.nodes[id].ending && !E.walkSpine(cid).path.includes(id));
  log(`## ${c.name} (${cid})\n`);

  // each style
  const byStyle = {};
  for (const style of Object.keys(STYLES)) {
    const n = style === "random" ? RUNS : Math.max(200, Math.floor(RUNS / 4));
    const hits = {};
    let score = 0, ok = 0, rolls = 0, threes = 0, decisions = 0;
    for (let i = 0; i < n; i++) {
      const r = play(cid, style, 1000 + i * 7 + style.length, false);
      if (!r) continue;
      ok++; hits[r.ending] = (hits[r.ending] || 0) + 1; score += r.score; rolls += r.rolls; threes += r.threes; decisions += r.decisions;
    }
    byStyle[style] = { n: ok, hits, mean: ok ? score / ok : 0, rolls: ok ? rolls / ok : 0, threes: ok ? threes / ok : 0, decisions: ok ? decisions / ok : 0 };
  }
  log(`| style | runs | mean score | most common ending | the settled ending | decisions | rolls | three-way |`);
  log(`|---|---|---|---|---|---|---|---|`);
  for (const [style, b] of Object.entries(byStyle)) {
    const top = Object.entries(b.hits).sort((a, z) => z[1] - a[1])[0];
    log(`| ${style} | ${b.n} | ${f1(b.mean)} | ${top ? top[0].replace(cid + "_end_", "") + " " + f1(pct(top[1], b.n)) + "%" : "-"} | ${settled ? f1(pct(b.hits[settled.id] || 0, b.n)) + "%" : "-"} | ${f1(b.decisions)} | ${f1(b.rolls)} | ${f1(b.threes)} |`);
  }
  const rand = byStyle.random;
  log(`\nEndings under random play:\n`);
  const rare = [];
  for (const e of endings) {
    const share = pct(rand.hits[e.id] || 0, rand.n);
    log(`- ${e.id.replace(cid + "_end_", "")} (${e.badge}): ${f1(share)}%${e.hardModeOnly ? " (hard mode only)" : ""}`);
    if (!e.hardModeOnly && share < 2) rare.push(`${e.id.replace(cid + "_end_", "")} ${f1(share)}%`);
  }
  if (rare.length) log(`\nUnder 2 per cent: ${rare.join(", ")}.`);

  // the value of each order: mean score of the runs that took it, against the others, under random play
  const stat = {};
  for (let i = 0; i < RUNS; i++) {
    const r = play(cid, "random", 1000 + i * 7 + "random".length, true);
    if (!r) continue;
    for (const t of r.taken) {
      const k = t.node + "/" + t.choice;
      const s = (stat[k] = stat[k] || { sum: 0, n: 0 });
      s.sum += r.score; s.n++;
    }
  }
  const gaps = [];
  for (const nid of nodeIds) {
    const node = c.nodes[nid];
    if (node.ending) continue;
    const resolved = E.resolveNode(nid, {}, E.emptyMeters(), E.emptyHardState());
    if (!resolved) continue;
    const vals = resolved.choices.map((ch) => stat[nid + "/" + ch.id]).map((s, i) => ({ id: resolved.choices[i].id, mean: s && s.n >= 30 ? s.sum / s.n : null, n: s ? s.n : 0 })).filter((x) => x.mean !== null);
    if (vals.length < 2) continue;
    vals.sort((a, z) => z.mean - a.mean);
    gaps.push({ node: nid, best: vals[0], worst: vals[vals.length - 1], gap: vals[0].mean - vals[vals.length - 1].mean });
  }
  gaps.sort((a, z) => z.gap - a.gap);
  const dominant = gaps.filter((g) => g.gap > GAP);
  log(`\nDecisions where one order scores more than ${GAP} points better than another (${dominant.length} of ${gaps.length}):\n`);
  for (const g of dominant.slice(0, 8)) log(`- ${g.node}: ${g.best.id} ${f1(g.best.mean)} against ${g.worst.id} ${f1(g.worst.mean)} (gap ${f1(g.gap)})`);
  if (!dominant.length) log("- none");

  // the detours
  const entered = {};
  for (let i = 0; i < Math.min(RUNS, 2000); i++) {
    const r = play(cid, "random", 50000 + i * 11, false);
    if (!r) continue;
    for (const v of r.visited) if (detours.includes(v)) entered[v] = (entered[v] || 0) + 1;
  }
  log(`\nDetours entered under random play (${Math.min(RUNS, 2000)} runs): ${detours.length ? detours.map((d) => `${d} ${f1(pct(entered[d] || 0, Math.min(RUNS, 2000)))}%`).join("; ") : "none"}\n`);
  summaryRows.push({ cid, name: c.name, random: rand, record: byStyle.record, dominant: dominant.length, decisions: gaps.length, rare });
}

log(`## Summary\n`);
log(`| command | random: mean score | the record: mean score | the record: settled ending | dominant decisions | endings under 2% |`);
log(`|---|---|---|---|---|---|`);
for (const s of summaryRows) {
  const settled = E.buildEndings().find((e) => e.campaignId === s.cid && e.badge === E.BADGES.SETTLED);
  log(`| ${s.name} | ${f1(s.random.mean)} | ${f1(s.record.mean)} | ${settled ? f1(pct(s.record.hits[settled.id] || 0, s.record.n)) + "%" : "-"} | ${s.dominant} of ${s.decisions} | ${s.rare.length} |`);
}
if (WRITE) { writeFileSync(join(ROOT, "..", "docs", "BALANCE.md"), out.join("\n") + "\n"); console.log("\nwritten docs/BALANCE.md"); }
