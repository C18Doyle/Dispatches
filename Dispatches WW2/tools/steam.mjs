#!/usr/bin/env node
// The files Steam needs from the game, generated from the game's own lists so that they cannot drift from it:
//   steam/achievements.json                 the achievements (part 45, ACHIEVEMENTS): API name, name and description in the nine languages
//   steam/input/game_actions_APPID.vdf      the Steam Input action manifest (src/shell-core.js, STEAM_INPUT_ACTIONS): one action set
// Rename the manifest to the real app id once there is one (docs/STEAM.md).
//   node tools/steam.mjs           check: the files are up to date and valid (in npm run test:fast)
//   node tools/steam.mjs --write   write them
import { createRequire } from "node:module";
import { pathToFileURL, fileURLToPath } from "node:url";
import { readFileSync, writeFileSync, existsSync, mkdirSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(ROOT, "package.json"));
const esbuild = require("esbuild");
const WRITE = process.argv.includes("--write");
const { loadFromJsx } = await import(pathToFileURL(join(ROOT, "../packages/testkit/src/load-campaigns.mjs")).href);
const { ACHIEVEMENTS } = loadFromJsx(esbuild, join(ROOT, "src/App.jsx"), ["ACHIEVEMENTS"]);

// shell-core.js, with React and the language layer stubbed (T() returns the English, as everywhere in the tools).
const out = join(mkdtempSync(join(tmpdir(), "steam-")), "shell-core.cjs");
await esbuild.build({
  entryPoints: [join(ROOT, "src/shell-core.js")],
  bundle: true,
  platform: "node",
  format: "cjs",
  outfile: out,
  logLevel: "error",
  plugins: [
    {
      name: "stubs",
      setup(b) {
        b.onResolve({ filter: /^(react|@dispatches\/i18n)$/ }, (a) => ({ path: a.path, namespace: "stub" }));
        b.onLoad({ filter: /.*/, namespace: "stub" }, (a) => ({
          contents: a.path === "react" ? "export const useState=()=>[],useEffect=()=>{},useRef=()=>({});" : "export const t=(s)=>s,T=(s)=>s,getLanguage=()=>'en';",
          loader: "js",
        }));
      },
    },
  ],
});
const { STEAM_INPUT_ACTIONS } = require(out);

// The game's languages and Steam's names for them (the API language codes of the Steamworks documentation).
const STEAM_LANG = { en: "english", de: "german", es: "spanish", fr: "french", it: "italian", ja: "japanese", "pt-BR": "brazilian", ru: "russian", "zh-Hans": "schinese" };
const tables = Object.fromEntries(
  Object.keys(STEAM_LANG)
    .filter((l) => l !== "en")
    .map((l) => [l, JSON.parse(readFileSync(join(ROOT, "src/i18n", l + ".json"), "utf8"))])
);
const tr = (lang, s, vars = {}) => {
  const raw = lang === "en" ? s : tables[lang][s] || null;
  return raw == null ? null : raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
};

const problems = [];
// ---- achievements ----
const achievements = ACHIEVEMENTS.map((a) => {
  const name = {};
  const desc = {};
  for (const [l, steam] of Object.entries(STEAM_LANG)) {
    const n = tr(l, a.name);
    const d = tr(l, a.desc);
    if (n) name[steam] = n;
    if (d) desc[steam] = d;
  }
  return { api: a.api, name, desc, hidden: false, icon: `icons/${a.api.toLowerCase()}.jpg`, iconLocked: `icons/${a.api.toLowerCase()}_locked.jpg` };
});
const seen = new Set();
for (const a of achievements) {
  if (!/^[A-Z0-9_]+$/.test(a.api) || a.api.length > 64) problems.push(`achievement ${a.api}: the API name must be capitals, digits and underscores, at most 64`);
  if (seen.has(a.api)) problems.push(`achievement ${a.api}: duplicate API name`);
  seen.add(a.api);
  if (!a.name.english || !a.desc.english) problems.push(`achievement ${a.api}: no English name or description`);
  if ((a.desc.english || "").length > 255) problems.push(`achievement ${a.api}: the description is over 255 characters`);
}
const achievementsJson = JSON.stringify({ note: "Generated by tools/steam.mjs from part 45 (ACHIEVEMENTS). Enter these in the Steamworks partner site; the game unlocks them through window.dispatchesSteam.unlockAchievement (docs/STEAM.md).", achievements }, null, 2) + "\n";

// ---- the Steam Input action manifest ----
const q = (s) => `"${String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const token = (id) => "Action_" + id;
const lines = [];
lines.push(`"In Game Actions"`, `{`, `\t"actions"`, `\t{`, `\t\t"Dispatches"`, `\t\t{`, `\t\t\t"title"\t${q("#Set_Dispatches")}`, `\t\t\t"Button"`, `\t\t\t{`);
for (const a of STEAM_INPUT_ACTIONS) {
  if (!/^[a-z0-9_]+$/.test(a.id)) problems.push(`input action ${a.id}: the name must be lower case, digits and underscores`);
  lines.push(`\t\t\t\t${q(a.id)}\t${q("#" + token(a.id))}`);
}
lines.push(`\t\t\t}`, `\t\t}`, `\t}`, `\t"localization"`, `\t{`);
for (const [l, steam] of Object.entries(STEAM_LANG)) {
  lines.push(`\t\t${q(steam)}`, `\t\t{`);
  const set = tr(l, "Dispatches WW2") || "Dispatches WW2";
  lines.push(`\t\t\t${q("Set_Dispatches")}\t${q(set)}`);
  for (const a of STEAM_INPUT_ACTIONS) {
    const s = tr(l, a.help, a.n ? { n: a.n } : {}) || tr("en", a.help, a.n ? { n: a.n } : {});
    lines.push(`\t\t\t${q(token(a.id))}\t${q(s)}`);
  }
  lines.push(`\t\t}`);
}
lines.push(`\t}`, `}`, ``);
const vdf = lines.join("\n");

// ---- write or check ----
const files = [
  [join(ROOT, "steam/achievements.json"), achievementsJson],
  [join(ROOT, "steam/input/game_actions_APPID.vdf"), vdf],
];
for (const [path, text] of files) {
  if (WRITE) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  } else if (!existsSync(path) || readFileSync(path, "utf8") !== text) {
    problems.push(`${path.slice(ROOT.length + 1)} is not up to date: run node tools/steam.mjs --write`);
  }
}
const missing = achievements.filter((a) => Object.keys(a.name).length < Object.keys(STEAM_LANG).length).length;
if (problems.length) {
  console.error(`steam: ${problems.length} problem(s)`);
  for (const p of problems) console.error("  " + p);
  process.exit(1);
}
console.log(
  `steam: ${achievements.length} achievements (${missing} with an English name only: the objectives' titles are not yet translated), ${STEAM_INPUT_ACTIONS.length} input actions in ${Object.keys(STEAM_LANG).length} languages${WRITE ? ", written" : ", up to date"}`
);
